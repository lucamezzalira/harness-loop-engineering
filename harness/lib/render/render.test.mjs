import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';
import { loadConfig } from '../config.mjs';
import { renderAdapter, renderRoleForTool } from './render.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const TOOLS = ['cursor', 'claude'];
const WRITE_TOOLS = ['Edit', 'Write', 'Bash'];

function parseFrontmatter(text) {
  const first = text.split('\n')[0];
  assert.equal(first, '---');
  const end = text.indexOf('\n---\n');
  assert.ok(end > 3, 'frontmatter closes');
  const data = parseYaml(text.slice(4, end));
  assert.equal(typeof data, 'object');
  assert.ok(data);
  return { data, rest: text.slice(end + 5) };
}

function toolList(value) {
  if (Array.isArray(value)) return value.map(String);
  if (typeof value === 'string') return value.split(',').map((s) => s.trim()).filter(Boolean);
  return [];
}

function seedRepo(tool) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'harness-render-role-'));
  fs.cpSync(path.join(ROOT, 'harness'), path.join(tmp, 'harness'), { recursive: true });
  fs.copyFileSync(path.join(ROOT, 'harness.yaml'), path.join(tmp, 'harness.yaml'));
  fs.writeFileSync(path.join(tmp, 'verify.sh'), '#!/bin/bash\n', { mode: 0o755 });
  fs.writeFileSync(path.join(tmp, 'AGENTS.md'), '# test\n');
  fs.writeFileSync(
    path.join(tmp, 'harness.local.yaml'),
    `tool: ${tool}\nprofile: default\nhooks:\n  enable: true\n`,
  );
  return tmp;
}

function binding() {
  return { tier: 'deep', modelId: 'claude-opus-5', provider: 'anthropic' };
}

test('A-01 rendered role files start with frontmatter name and description', async () => {
  for (const tool of TOOLS) {
    const tmp = seedRepo(tool);
    try {
      const cfg = loadConfig(tmp);
      cfg.tool = tool;
      cfg.hooks = { enable: true };
      await renderAdapter(tmp, cfg);
      const dirName = tool === 'cursor' ? '.cursor' : '.claude';
      const agents = path.join(tmp, dirName, 'agents');
      const files = fs.readdirSync(agents).filter((name) => name.endsWith('.md'));
      assert.ok(files.length >= 5, `${tool} rendered roles`);
      for (const name of files) {
        const text = fs.readFileSync(path.join(agents, name), 'utf8');
        const { data, rest } = parseFrontmatter(text);
        assert.equal(typeof data.name, 'string');
        assert.ok(data.name.length > 0, `${tool}/${name} name`);
        assert.equal(typeof data.description, 'string');
        assert.ok(data.description.length > 0, `${tool}/${name} description`);
        assert.equal(data.model, undefined, `${tool}/${name} omits model`);
        assert.match(rest, /<!--[\s\S]*GENERATED BY HARNESS/);
        assert.doesNotMatch(text.slice(0, text.indexOf('\n---\n')), /GENERATED BY HARNESS/);
      }
    } finally {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
  }
});

test('A-02 read-only roles are readonly on Cursor and have no write tools on Claude', () => {
  const rolesDir = path.join(ROOT, 'harness', 'roles');
  const roles = fs
    .readdirSync(rolesDir)
    .filter((name) => name.endsWith('.md') && name !== 'README.md');
  assert.ok(roles.length > 0);

  for (const file of roles) {
    const role = file.replace(/\.md$/, '');
    const src = path.join(rolesDir, file);
    const raw = fs.readFileSync(src, 'utf8');
    const { data } = parseFrontmatter(raw);
    const sourceTools = toolList(data.tools).map((t) => t.toLowerCase());
    const readOnly = sourceTools.length > 0 && sourceTools.every((t) => t === 'read');

    const cursor = parseFrontmatter(renderRoleForTool('cursor', role, src, binding())).data;
    const claude = parseFrontmatter(renderRoleForTool('claude', role, src, binding())).data;
    const claudeTools = toolList(claude.tools);

    if (readOnly) {
      assert.equal(cursor.readonly, true, `${role} cursor readonly`);
      for (const banned of WRITE_TOOLS) {
        assert.ok(!claudeTools.includes(banned), `${role} claude omits ${banned}`);
      }
      assert.deepEqual(claudeTools, ['Read', 'Grep', 'Glob'], `${role} claude read tools`);
    } else {
      assert.notEqual(cursor.readonly, true, `${role} is not marked readonly`);
    }
    assert.equal(cursor.model, undefined);
    assert.equal(claude.model, undefined);
  }

  const writer = path.join(rolesDir, 'test-writer.md');
  const mapped = toolList(
    parseFrontmatter(renderRoleForTool('claude', 'test-writer', writer, binding())).data.tools,
  );
  assert.deepEqual(mapped, ['Read', 'Grep', 'Glob', 'Edit', 'Write', 'Bash']);
});

test('A-04 checker roles are deep read-only and render for Cursor and Claude', async () => {
  for (const role of ['acceptance-checker', 'integrity-checker']) {
    const src = path.join(ROOT, 'harness', 'roles', `${role}.md`);
    const source = parseFrontmatter(fs.readFileSync(src, 'utf8')).data;
    assert.equal(source.name, role);
    assert.equal(typeof source.description, 'string');
    assert.ok(source.description.length > 0);
    assert.equal(source.tier, 'deep');
    assert.deepEqual(
      toolList(source.tools).map((t) => t.toLowerCase()),
      ['read'],
    );

    for (const tool of ['cursor', 'claude']) {
      const rendered = parseFrontmatter(renderRoleForTool(tool, role, src, binding())).data;
      assert.equal(rendered.name, role);
      assert.ok(rendered.description);
      assert.equal(rendered.model, undefined);
      if (tool === 'cursor') assert.equal(rendered.readonly, true);
      if (tool === 'claude') {
        const tools = toolList(rendered.tools);
        for (const banned of WRITE_TOOLS) {
          assert.ok(!tools.includes(banned), `${role} ${banned}`);
        }
        assert.deepEqual(tools, ['Read', 'Grep', 'Glob']);
      }
    }
  }

  for (const tool of ['cursor', 'claude']) {
    const tmp = seedRepo(tool);
    try {
      const cfg = loadConfig(tmp);
      cfg.tool = tool;
      const dirName = tool === 'cursor' ? '.cursor' : '.claude';
      await renderAdapter(tmp, cfg);
      for (const role of ['acceptance-checker', 'integrity-checker']) {
        const file = path.join(tmp, dirName, 'agents', `${role}.md`);
        assert.equal(fs.existsSync(file), true, file);
        const fm = parseFrontmatter(fs.readFileSync(file, 'utf8')).data;
        assert.equal(fm.name, role);
        assert.ok(fm.description);
      }
    } finally {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
  }
});

test('A-03 render check passes after a fresh render', async () => {
  const tmp = seedRepo('cursor');
  try {
    const cfg = loadConfig(tmp);
    cfg.tool = 'cursor';
    cfg.hooks = { enable: true };
    await renderAdapter(tmp, cfg);
    const checked = await renderAdapter(tmp, cfg, { checkOnly: true });
    assert.equal(checked.ok, true);
    assert.equal(checked.tool, 'cursor');
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
});
