#!/usr/bin/env node
/**
 * Walk docs/adr/NNNN-*.md, rewrite docs/adr/README.md, sync superseded-by links.
 * Exit 2 on duplicate ids or malformed frontmatter (harness-wrong).
 *
 * Flags:
 *   --check  generate README in memory (and sync check only); exit 2 if README differs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const ROOT =
  process.env.HARNESS_ROOT || path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ADR_DIR = process.env.ADR_DIR || path.join(ROOT, 'docs', 'adr');
const OUT = path.join(ADR_DIR, 'README.md');
const CHECK = process.argv.includes('--check');

const REQUIRED = [
  'id',
  'title',
  'status',
  'date',
  'tags',
  'touches',
  'supersedes',
  'superseded-by',
];

function fail(msg) {
  console.error(msg);
  process.exit(2);
}

function parseFrontmatter(filePath, text) {
  if (!text.startsWith('---')) {
    fail(`${filePath}: missing YAML frontmatter opener`);
  }
  const end = text.indexOf('\n---', 3);
  if (end < 0) fail(`${filePath}: missing YAML frontmatter closer`);
  const raw = text.slice(3, end).trim();
  let data;
  try {
    data = parseYaml(raw);
  } catch (e) {
    fail(`${filePath}: malformed frontmatter: ${e.message}`);
  }
  if (!data || typeof data !== 'object') fail(`${filePath}: frontmatter is not a mapping`);
  return { data, bodyStart: end + 4 };
}

function listAdrFiles() {
  if (!fs.existsSync(ADR_DIR)) return [];
  return fs
    .readdirSync(ADR_DIR)
    .filter((n) => /^\d{4}-.+\.md$/.test(n))
    .sort()
    .map((n) => path.join(ADR_DIR, n));
}

function asList(v) {
  if (v == null || v === '') return [];
  if (Array.isArray(v)) return v;
  return [v];
}

function firstSummary(text) {
  const { bodyStart } = parseFrontmatter('adr', text);
  const body = text.slice(bodyStart);
  for (const line of body.split('\n').map((l) => l.trim())) {
    if (!line || line.startsWith('#')) continue;
    return line.length > 100 ? `${line.slice(0, 97)}…` : line;
  }
  return '';
}

function loadAll() {
  const byId = new Map();
  const rows = [];
  for (const abs of listAdrFiles()) {
    const rel = path.relative(ROOT, abs);
    const text = fs.readFileSync(abs, 'utf8');
    const { data } = parseFrontmatter(rel, text);
    for (const k of REQUIRED) {
      if (!(k in data)) fail(`${rel}: missing required field "${k}"`);
    }
    const id = String(data.id).padStart(4, '0');
    if (!/^\d{4}$/.test(String(data.id))) {
      fail(`${rel}: id must be four-digit zero-padded, got "${data.id}"`);
    }
    const fileId = path.basename(abs).slice(0, 4);
    if (fileId !== id) fail(`${rel}: id "${data.id}" does not match filename prefix ${fileId}`);
    if (byId.has(id)) fail(`duplicate ADR id ${id}: ${byId.get(id)} and ${rel}`);
    byId.set(id, rel);
    rows.push({
      abs,
      rel,
      id,
      title: data.title,
      status: data.status,
      tags: asList(data.tags),
      touches: asList(data.touches),
      supersedes: asList(data.supersedes).map((x) => String(x).padStart(4, '0')),
      supersededBy: data['superseded-by'] ? String(data['superseded-by']).padStart(4, '0') : '',
      summary: firstSummary(text),
      text,
    });
  }
  return { rows };
}

function rewriteField(text, field, value) {
  const end = text.indexOf('\n---', 3);
  const fm = text.slice(0, end + 4);
  const body = text.slice(end + 4);
  const quoted = value === '' ? '""' : `"${value}"`;
  const re = new RegExp(`^${field}:.*$`, 'm');
  const nextFm = re.test(fm)
    ? fm.replace(re, `${field}: ${quoted}`)
    : fm.replace(/\n---\s*$/, `\n${field}: ${quoted}\n---\n`);
  return nextFm + body;
}

function syncSupersededBy(rows, write) {
  const fromSupersedes = new Map();
  for (const r of rows) {
    for (const old of r.supersedes) {
      if (fromSupersedes.has(old) && fromSupersedes.get(old) !== r.id) {
        fail(`ADR ${old} superseded by both ${fromSupersedes.get(old)} and ${r.id}`);
      }
      fromSupersedes.set(old, r.id);
    }
  }
  for (const r of rows) {
    const expected = fromSupersedes.get(r.id) || '';
    if (expected && r.supersededBy !== expected) {
      if (!write) {
        fail(
          `${r.rel}: superseded-by should be "${expected}" (from supersedes links); run node scripts/build-adr-index.mjs`,
        );
      }
      const updated = rewriteField(r.text, 'superseded-by', expected);
      fs.writeFileSync(r.abs, updated);
      r.supersededBy = expected;
      r.text = updated;
      console.error(`synced ${r.rel}: superseded-by → ${expected}`);
    }
  }
}

function renderReadme(rows) {
  const lines = [
    '<!-- Generated by scripts/build-adr-index.mjs; do not edit by hand. -->',
    '',
    '# Architecture Decision Records',
    '',
    'Standing decisions for this repository. Agents: read this index, match `touches`',
    'to paths you will change, then read those ADRs in full before editing.',
    '',
    'New ADR: copy `TEMPLATE.md` to `NNNN-kebab-title.md`, fill frontmatter, run',
    '`node scripts/build-adr-index.mjs`.',
    '',
    '| Number | Title | Status | Tags | Touches | Summary |',
    '| ------ | ----- | ------ | ---- | ------- | ------- |',
  ];
  for (const r of rows) {
    const status =
      r.status === 'superseded' ? `~~${r.status}~~ → ${r.supersededBy || '?'}` : r.status;
    const title = r.status === 'superseded' ? `~~${r.title}~~` : r.title;
    const tags = r.tags.join(', ');
    const touches = r.touches.map((t) => `\`${t}\``).join(', ');
    const link = `[${r.id}](./${path.basename(r.abs)})`;
    lines.push(
      `| ${link} | ${title} | ${status} | ${tags} | ${touches} | ${r.summary.replace(/\|/g, '\\|')} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

function main() {
  const { rows } = loadAll();
  syncSupersededBy(rows, !CHECK);
  const md = renderReadme(rows);
  if (CHECK) {
    if (!fs.existsSync(OUT)) fail('docs/adr/README.md missing; run: node scripts/build-adr-index.mjs');
    const committed = fs.readFileSync(OUT, 'utf8');
    if (committed !== md) {
      fail(
        'docs/adr/README.md differs from generator output (hand-edit or stale).\nRun: node scripts/build-adr-index.mjs',
      );
    }
    console.log(`adr-index ok (${rows.length} ADRs)`);
    return;
  }
  fs.writeFileSync(OUT, md);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${rows.length} ADRs)`);
}

main();
